// t('key', { n: 3 }) in the given language
export function translator(lang) {
  const i = IX[normLang(lang)];
  return (key, vars) => {
    let s = D[key] ? D[key][i] ?? D[key][0] : key;
    if (vars) for (const k in vars) s = s.split('{' + k + '}').join(vars[k]);
    return s;
  };
}
